import path from 'node:path';
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';

/**
 * Copies the files that `playground-elements` loads at runtime from `sandboxBaseUrl` into the host's
 * static folder.
 *
 * The sandbox only loads two files from that location, and both are self-contained (no further
 * imports), so we do not need to ship the whole ~12MB package:
 *  - `playground-service-worker-proxy.html` — registers the service worker and hands it a port
 *  - `playground-service-worker.js` — the service worker itself
 *
 * Astro's dev server 404s `.html` files served from `node_modules`, and `playground-elements`
 * resolves the proxy relative to `sandboxBaseUrl`, so both files must sit in the same static folder.
 */
const SANDBOX_FILES = ['playground-service-worker-proxy.html', 'playground-service-worker.js'];
const CONFIG_FILE = 'playground-sandbox-config.js';

/**
 * Writes the posture of this deployment next to the worker.
 *
 * The worker reads this file itself (`importScripts`) and only then sets a `Content-Security-Policy` on the
 * documents it serves. That policy is the mitigation for running the sandbox on the *same* origin — an explicit
 * opt-in, `PUBLIC_SAME_ORIGIN_SANDBOX=true`, for a deployment without a second host — where the browser is not
 * a boundary and the policy is all there is. With the sandbox on its own origin (the default, and the upstream
 * design) the worker behaves exactly as it always did. The policy can be overridden with
 * `PLAYGROUND_SAME_ORIGIN_CSP`, so tuning it never means touching the patch.
 *
 * The comment appended to the worker is not decoration: `importScripts` only re-runs when the worker script
 * itself changes, so without it flipping the posture would leave the previous config in place.
 * @param {string} destination
 */
async function writeSandboxPosture(destination) {
  const sameOrigin = process.env.PUBLIC_SAME_ORIGIN_SANDBOX === 'true';
  const policy = process.env.PLAYGROUND_SAME_ORIGIN_CSP;
  const config = [
    '// Generated by generateSandboxAssets.js — the posture of this deployment.',
    `self.__PG_SAME_ORIGIN__ = ${sameOrigin};`,
    policy ? `self.__PG_SAME_ORIGIN_CSP__ = ${JSON.stringify(policy)};` : '',
    '',
  ]
    .filter(line => line !== '')
    .join('\n');
  await fs.promises.writeFile(path.join(destination, CONFIG_FILE), `${config}\n`);

  const workerPath = path.join(destination, 'playground-service-worker.js');
  const worker = await fs.promises.readFile(workerPath, 'utf8');
  const postureHash = createHash('sha256').update(config).digest('hex').slice(0, 12);
  await fs.promises.writeFile(workerPath, `${worker}\n/* sandbox posture ${postureHash} */\n`);
  // eslint-disable-next-line no-console
  console.log(
    `Sandbox posture: ${sameOrigin ? 'same origin (opt-in, policy set by the worker)' : 'own origin (browser is the boundary)'}`,
  );
}

/**
 * @returns {string} the `--destination` folder
 */
function getDestination() {
  const index = process.argv.indexOf('--destination');
  const destination = index === -1 ? undefined : process.argv[index + 1];
  if (!destination) {
    throw new Error('Please provide a --destination folder for the sandbox assets');
  }
  return destination;
}

async function generateSandboxAssets() {
  const destination = getDestination();
  const require = createRequire(import.meta.url);
  // `main` is `playground-ide.js` at the package root, so its dirname is the package folder.
  const playgroundElementsDir = path.dirname(require.resolve('playground-elements'));

  await fs.promises.mkdir(destination, { recursive: true });
  for (const file of SANDBOX_FILES) {
    await fs.promises.copyFile(path.join(playgroundElementsDir, file), path.join(destination, file));
  }
  await writeSandboxPosture(destination);
}

generateSandboxAssets();
